// Interface copy in English and Bangla.

export const LOCALES = ["en", "bn"] as const;
export type Locale = (typeof LOCALES)[number];

/**
 * The language last picked with the English / বাংলা switch. Public pages take theirs from ?lang; the
 * signed-in areas (the business dashboard) have no ?lang in their links, so they read this (KAN-328).
 */
export const LANGUAGE_COOKIE = "sb_lang";

export function resolveLocale(raw: string | string[] | undefined): Locale {
    const value = Array.isArray(raw) ? raw[0] : raw;
    return value === "bn" ? "bn" : "en";
}

/** Appends the locale parameter to a path, preserving existing query values. */
export function localeHref(path: string, locale: Locale): string {
    if (locale === "en") return path;
    const [base, hash] = path.split("#");
    const withLang = base.includes("?") ? `${base}&lang=bn` : `${base}?lang=bn`;
    return hash === undefined ? withLang : `${withLang}#${hash}`;
}

// Picks the localised value, falling back to the other language so a field is never empty.
export function pick(
    locale: Locale,
    english: string | null | undefined,
    bangla: string | null | undefined
): string {
    if (locale === "bn" && bangla) return bangla;
    return english ?? bangla ?? "";
}

